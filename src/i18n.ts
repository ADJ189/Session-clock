const LOCALES: Record<Locale, Strings> = { en, es, fr, de, ja, ko, pt, hi };

const STORAGE_KEY = "sc_locale";
let _current: Locale = (safeGet(STORAGE_KEY) as Locale) || detectLocale();

function detectLocale(): Locale {
  const lang = navigator.language.slice(0, 2).toLowerCase();
  const map: Record<string, Locale> = {
    en: "en",
    es: "es",
    fr: "fr",
    de: "de",
    ja: "ja",
    ko: "ko",
    pt: "pt",
    hi: "hi",
  };
  return map[lang] ?? "en";
}

export function t(): Strings {
  return LOCALES[_current] ?? LOCALES.en;
}
export function getLocale(): Locale {
  return _current;
}
export function setLocale(l: Locale) {
  _current = l;
  localStorage.setItem(STORAGE_KEY, l);
  // Dispatch event so UI can re-render
  window.dispatchEvent(new CustomEvent("sc:locale", { detail: l }));
}
